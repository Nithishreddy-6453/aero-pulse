const HOTSPOT_TEMPLATE_MAP = new Map<string, CityHotspotTemplate[]>(
  PRESET_CITY_CONFIGS.map((c) => [c.id, c.hotspotTemplates])
);

function buildScaledHotspots(
  cityId: string,
  aqi: number,
  pm25: number,
  no2: number
): CityHotspot[] {
  const templates = HOTSPOT_TEMPLATE_MAP.get(cityId) ?? GENERIC_HOTSPOT_TEMPLATES;
  const safeAqi = Math.max(12, aqi);
  const safePm25 = Math.max(3, pm25);
  const safeNo2 = Math.max(2, no2);

  return templates.map((t) => ({
    id: `${cityId}-${t.id}`,
    name: t.name,
    zoneType: t.zoneType,
    x: t.x,
    y: t.y,
    aqi: Math.max(8, Math.round(safeAqi * t.aqiMultiplier)),
    pm25: Number(Math.max(1, safePm25 * t.pm25Multiplier).toFixed(1)),
    no2: Number(Math.max(1, safeNo2 * t.no2Multiplier).toFixed(1)),
    radius: t.radius,
    note: t.note,
  }));
}


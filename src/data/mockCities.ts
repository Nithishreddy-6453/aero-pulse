export function createDynamicIndianCity(params: {
  id: string;
  name: string;
  state: string;
  lat: number;
  lng: number;
  locality?: string;
}): CityAirProfile {
  const cleanState = params.state || 'India';
  return {
    id: params.id,
    name: params.name,
    state: cleanState,
    center: { lat: params.lat, lng: params.lng },
    aqi: 0,
    severity: 'moderate',
    severityLabel: 'SYNCING',
    pm25: 0,
    pm10: 0,
    no2: 0,
    o3: 0,
    indoorCo2: 650,
    safeWindowLabel: 'Calculating...',
    safeStartIdx: 8,
    safeEndIdx: 9,
    defaultOrigin: params.locality ? `${params.locality}, ${params.name}` : params.name,
    defaultDestination: `${params.name} Railway Station`,
    colonyName: params.locality ? `${params.locality} RWA` : `${params.name} RWA`,
    hourlyTimeline: [],
    hotspots: buildScaledHotspots(params.id, 0, 0, 0),
    isLive: false,
  };
}

export function applyLiveAirQualityToCity(
  city: CityAirProfile,
  live: LiveAirQualityResponse
): CityAirProfile {
  return {
    ...city,
    aqi: live.aqi,
    severity: live.severity,
    severityLabel: live.severityLabel,
    pm25: live.pm25,
    pm10: live.pm10,
    no2: live.no2,
    o3: live.o3,
    indoorCo2: live.indoorCo2Estimate,
    safeWindowLabel: live.safeWindowLabel,
    safeStartIdx: live.safeStartIdx,
    safeEndIdx: live.safeEndIdx,
    hourlyTimeline: live.hourlyTimeline,
    hotspots: buildScaledHotspots(city.id, live.aqi, live.pm25, live.no2),
    isLive: true,
    fetchedAtIso: live.fetchedAtIso,
    fetchedAtLabel: live.fetchedAtLabel,
  };
}

